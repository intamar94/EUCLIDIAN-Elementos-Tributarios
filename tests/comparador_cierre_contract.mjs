import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const js=readFileSync('comparador.js','utf8');
const ctx={window:{},URL};vm.runInNewContext(js,ctx);
const {borrador,preparar}=ctx.window.EuclidianComparador;
const base={id:'a',numero_resolucion:'REF-A',titulo:'Ejemplo',tipo_documento:'concepto',enlace_oficial:'https://normograma.dian.gov.co/a',texto_completo:'Una fuente de ejemplo con texto suficiente para poder preparar un pasaje documental trazable.'};
const a=preparar(base),b=preparar({...base,id:'b',numero_resolucion:'REF-B',enlace_oficial:'https://normograma.dian.gov.co/b'});
const fecha='2026-10-19T17:40:00Z';
let salida=borrador(a,b,'La regla anterior establece A.','La regla posterior establece B.',fecha);
assert.match(salida,/Generado \(UTC\): 2026-10-19T17:40:00.000Z/);
assert.match(salida,/Revisión jurídica: PENDIENTE/);
assert.match(salida,/versiones jurídicas: NO APROBADAS/);
assert.match(salida,/no identificador de versión jurídica/);
assert.match(salida,/Fuente oficial: https:\/\/normograma.dian.gov.co\/a/);
assert.match(salida,/Registro EUCLIDIAN: b/);
assert.match(salida,/La regla anterior establece A\./);
assert.match(salida,/La regla posterior establece B\./);
assert.match(salida,/anterior A\./);
assert.match(salida,/posterior B\./);
assert.match(salida,/Pasaje editado respecto del extracto cargado: SÍ/);
salida=borrador(a,b,a.fragmento,b.fragmento,fecha);
assert.match(salida,/Pasaje editado respecto del extracto cargado: NO/);
assert.match(salida,/\(Ninguna en el tramo evaluado\)/);
salida=borrador(a,b,'a '.repeat(400),'a '.repeat(320)+'distinto',fecha);
assert.match(salida,/comparación recortada/);
assert.match(salida,/distinto/,'El pasaje exportado conserva palabras no comparadas');
assert.doesNotMatch(salida.split('PALABRAS AUSENTES')[1].split('TEXTO B')[0],/distinto/);
assert.throws(()=>borrador(a,a,'a','b',fecha),/distintos/);
assert.throws(()=>borrador(a,b,' ','b',fecha),/dos fragmentos/);
assert.throws(()=>borrador({...a,url:'https://dian.gov.co.evil.invalid'},b,'a','b',fecha),/oficial/);
assert.throws(()=>borrador(a,b,'a','b','incorrecta'),/inválida/);
assert.match(js,/data-comp-exportar/);
assert.match(js,/URL.revokeObjectURL/);
assert.doesNotMatch(js,/fetch\(|localStorage|sessionStorage|XMLHttpRequest|sendBeacon/);
console.log('M2: borrador local con fuentes A/B, pasajes editados, límites explícitos y revisión pendiente OK');
