import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const listeners={};let status='';
const campo={value:'dato anterior'},contador={textContent:'1 / 18 fuentes'};
const document={readyState:'loading',addEventListener(k,fn){listeners[k]=fn;},querySelectorAll(){return [campo];},getElementById(id){return id==='expEstado'?{set textContent(v){status=v;}}:id==='expContador'?contador:null;}};
