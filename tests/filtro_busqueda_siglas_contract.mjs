import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {filtroBusquedaDocumentos} from '../lib/filtro-busqueda-documentos.js';
function interpret(q){const f=filtroBusquedaDocumentos(q);const n=f.indexOf('=');return {field:f.slice(1,n),filter:decodeURIComponent(f.slice(n+1))};}
const iva=interpret('IVA');
assert.equal(iva.field,'or');
assert.equal(iva.filter,'(and(contenido.ilike.*IVA*,contenido.plfts(spanish).IVA),and(descripcion_limpia.ilike.*IVA*,descripcion_limpia.plfts(spanish).IVA))');
assert.equal((iva.filter.match(/\.plfts\(spanish\)/g)||[]).length,2);
assert.equal((iva.filter.match(/\.ilike\.\*IVA\*/g)||[]).length,2);
const sigla=interpret('UVT');
assert.match(sigla.filter,/contenido\.ilike\.\*UVT\*/);
assert.match(sigla.filter,/descripcion_limpia\.plfts\(spanish\)\.UVT/);
const de2=interpret('UV');assert.doesNotMatch(de2.filter,/ilike/);
assert.match(de2.filter,/plfts/);
const doc=interpret('DIAN-OFICIO-141-2025');
assert.equal(doc.field,'numero_resolucion');
assert.equal(doc.filter,'eq.DIAN-OFICIO-141-2025');
const normal=interpret('retención en la fuente');
assert.match(normal.filter,/numero_resolucion\.ilike/);
assert.match(normal.filter,/titulo\.ilike/);
const minuscula=interpret('iva');assert.match(minuscula.filter,/titulo\.ilike/);
assert.equal(filtroBusquedaDocumentos('  '),'');
assert.doesNotMatch(interpret('IVA,);*%').filter,/\);/);
assert.doesNotMatch(interpret('IVA,);*%').filter,/%/);
assert.ok(filtroBusquedaDocumentos('X'.repeat(300)).length<1000);
const api=readFileSync('api/documentos.js','utf8');
assert.match(api,/import \{filtroBusquedaDocumentos\} from '\.\.\/lib\/filtro-busqueda-documentos\.js'/);
assert.match(api,/if\(!doc&&q\)filtro\+=filtroBusquedaDocumentos\(q\)/);
assert.match(api,/&publicado_cliente=is\.true/);
assert.match(api,/autorizarConsulta\(req\)/);
assert.match(api,/consulta_lenta/);
const lib=readFileSync('lib/filtro-busqueda-documentos.js','utf8');
assert.doesNotMatch(lib,/fetch\(|SUPABASE_SERVICE_KEY|localStorage|new Function|create extension|CREATE INDEX/i);
console.log('Contrato búsqueda: siglas FTS con prefiltro índice, número, entrada maliciosa, acceso y fallback OK');
