import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const source=readFileSync('expedientes.js','utf8');
const app=readFileSync('app.html','utf8'),bloques=readFileSync('bloques.js','utf8');
const css=readFileSync('expedientes.css','utf8'),auth=readFileSync('auth.js','utf8');
const contexto={window:{},URL,Date,JSON};vm.runInNewContext(source,contexto);
const f=contexto.window.EuclidianExpedientes;
assert.equal(typeof f.nuevo,'function');
assert.match(app,/id="expedientesPanel"/);
assert.match(app,/id="expImportar"/);
assert.match(app,/src="\/expedientes\.js" defer/);
assert.ok(app.indexOf('/expedientes.js')<app.indexOf('/bloques.js'));
assert.match(bloques,/EuclidianExpedientes\?\.panel\(d\)/);
assert.match(auth,/function authMostrarPuerta\(\)\{window\.EuclidianExpedientes\?\.limpiar\(\)/);
assert.match(app,/<img class="ilustracion" src="\/euclides\.png"/);
assert.match(app,/No introduzcas NIT, declaraciones, importes ni datos personales reales/);
assert.doesNotMatch(source,/localStorage|sessionStorage|fetch\(|SUPABASE_SERVICE_KEY|XMLHttpRequest|navigator\.sendBeacon/);
assert.match(css,/@media\(max-width:700px\)/);
assert.match(css,/@media\(max-width:380px\)/);
assert.match(css,/focus-visible/);

const id=f.nuevo('Informe IVA hipotético');
assert.match(id,/^exp-\d+$/);
assert.equal(f.estadoActual().campos.titulo,'Informe IVA hipotético');
assert.equal(f.modificar('pregunta','¿Cómo se aplica una excepción?'),true);
assert.equal(f.modificar('hechos','Caso ficticio sin cliente real'),true);
assert.equal(f.modificar('conclusion','Borrador preliminar, sin aprobación.'),true);
assert.equal(f.modificar('autorizacion','forzada'),false);
assert.equal(f.modificar('hechos','X'.repeat(3800)),true);
assert.equal(f.estadoActual().campos.hechos.length,3000);
const doc={id:'123e4567-e89b-42d3-a456-426614174000',
 numero_resolucion:'DIAN-OFICIO-52-2025',titulo:'Criterio DIAN en un supuesto',
 enlace_oficial:'https://normograma.dian.gov.co/dian/compilacion/docs/ejemplo.htm',
 tipo_documento:'oficio'};
assert.match(f.panel(doc),/Añadir a expediente/);
assert.equal(f.panel({...doc,enlace_oficial:'http://dian.gov.co/docs/a'}),'');
assert.equal(f.panel({...doc,enlace_oficial:'https://dian.gov.co.evil.invalid/docs/a'}),'');
assert.equal(f.panel({...doc,tipo_documento:'boletin'}),'');
const attach={url:doc.enlace_oficial,ref:doc.numero_resolucion,titulo:doc.titulo};
assert.equal(f.agregarFuente(attach),true);
assert.equal(f.agregarFuente(attach),false);
assert.equal(f.estadoActual().fuentes.length,1);
const backup=f.respaldo();
assert.match(backup,/euclidian-expediente-v1/);
assert.match(backup,/borrador_sin_revision/);
const borrador=f.informe();
assert.match(borrador,/BORRADOR SIN REVISIÓN/);
assert.match(borrador,/NO APROBADA/);
assert.match(borrador,/criterio/i);
assert.match(borrador,/normativa|normativo/i);
assert.doesNotMatch(borrador,/estado: aprobado/i);
const importado=f.importar(backup);
assert.notEqual(importado,id);
assert.equal(f.estadoActual().fuentes[0].cotejo,false);
assert.equal(f.estadoActual().estado,'borrador_sin_revision');
assert.equal(f.estadoActual().campos.pregunta,'¿Cómo se aplica una excepción?');
const falsificado=JSON.parse(backup);
falsificado.estado='aprobado';falsificado.fuentes[0].cotejo=true;falsificado.fuentes[0].revision_humana=true;
f.importar(JSON.stringify(falsificado));
assert.equal(f.estadoActual().estado,'borrador_sin_revision');
assert.equal(f.estadoActual().fuentes[0].cotejo,false);
const hostile=JSON.parse(backup);hostile.fuentes[0].url='https://dian.gov.co.evil.invalid/';
assert.throws(()=>f.importar(JSON.stringify(hostile)),/fuente inválida/i);
assert.throws(()=>f.importar('x'.repeat(210000)),/200 KB/);
assert.throws(()=>f.importar('{"formato":"falso"}'),/Formato de expediente/);
const dangerous=JSON.parse(backup);dangerous.campos.titulo='<svg onload=alert(1)>';
const nid=f.importar(JSON.stringify(dangerous));
assert.equal(f.estadoActual().campos.titulo,'<svg onload=alert(1)>');
assert.equal(f.seleccionar(id),true);
assert.equal(f.removerFuente(0),true);
assert.equal(f.estadoActual().fuentes.length,0);
assert.equal(f.seleccionar('no-existe'),false);
f.limpiar();
assert.equal(f.estadoActual(),null);
assert.throws(()=>f.respaldo(),/No hay expediente/);
assert.throws(()=>f.agregarFuente(attach),/Crea un expediente/);
assert.equal(f.urlDian('https://dian.gov.co.evil.com/foo'),'');
assert.equal(f.urlDian('https://usr:pwd@normograma.dian.gov.co/foo'),'');
console.log('Expedientes M3: in-memory, 200KB import, fuga, revisión fraudulenta, fuentes DIAN y borrado al salir OK');
