import assert from 'node:assert/strict';
import vm from 'node:vm';
import {readFileSync} from 'node:fs';
const source=readFileSync(new URL('../exogena.js',import.meta.url),'utf8');
const context={window:{},document:{readyState:'loading',addEventListener(){},getElementById(){return null;}},TextEncoder};
vm.runInNewContext(source,context);
const api=context.window.EuclidianExogena;
assert.equal(api.revisar(api.ejemplo).valido,true);
assert.equal(api.revisar('\uFEFF'+api.ejemplo).registros,2);
assert.equal(api.revisar('fila_id,concepto_ficticio,importe\n').valido,false);
assert.equal(api.revisar('').errores[0].campo,'encabezados');
assert.equal(api.revisar('fila_id,concepto_ficticio,importe\n,,').valido,false);
assert.equal(api.revisar('a,b,c\n1,2,3').valido,false);
assert.equal(api.revisar('fila_id;concepto_ficticio;importe').valido,false);
const prefijo='fila_id,concepto_ficticio,importe\n';
const fila='DEMO-001,DEMO_SERVICIO,1.00\n';
assert.match(api.revisar(prefijo+fila+fila).errores[0].motivo,/repetido/);
assert.match(api.revisar(prefijo+'DEMO-001,DEMO_BIEN\n').errores[0].motivo,/columnas/);
for(const v of ['1,00','1.001','-1.00','1e3','NaN','Infinity','001.00','1000000000000.00',' 1.00'])assert.equal(api.revisar(prefijo+'DEMO-001,DEMO_BIEN,"'+v+'"').valido,false,v);
for(const v of ['0.00','1250.00','999999999999.99'])assert.equal(api.revisar(prefijo+'DEMO-001,DEMO_BIEN,'+v).valido,true,v);
for(const v of ['=SUM(A1:A2)','+1','@NOW()','  =1','\t=1'])assert.match(api.revisar(prefijo+'DEMO-001,"'+v+'",1.00').errores[0].motivo,/fórmula/);
assert.equal(api.revisar(prefijo+'123456789,DEMO_BIEN,1.00').valido,false);
assert.equal(api.parsearCSV('a,"b,b","c""c"')[0].celdas[2],'c"c');
assert.equal(api.parsearCSV('a,"b\nb",c\nx,y,z')[1].numero,3);
assert.equal(api.parsearCSV('a,b,c\r\nx,y,z')[1].numero,2);
assert.throws(()=>api.parsearCSV('a,"bad,c'),/cerrar comillas/);
assert.throws(()=>api.parsearCSV('a,"b"extra,c'),/después/);
assert.throws(()=>api.parsearCSV('a,b"c,d'),/comillas dentro/);
assert.throws(()=>api.parsearCSV('é'.repeat(100001)),/200 KB/);
assert.throws(()=>api.parsearCSV(Array(22).fill('a').join(',')),/columnas/);
assert.throws(()=>api.revisar(prefijo+fila.repeat(1001)),/1000 registros/);
assert.equal(api.revisar(prefijo+fila.repeat(1000)).errores.length,100);
assert.equal(api.revisar(prefijo+fila.repeat(1000)).totalErrores,999);
assert.equal(api.revisar(prefijo+'<script>,DEMO_BIEN,1.00').valido,false);
assert.doesNotMatch(source,/innerHTML|localStorage|sessionStorage|fetch\(|XMLHttpRequest|document\.cookie/);
api.limpiar();
console.log('M7: esquema ficticio, CSV entrecomillado, líneas físicas, duplicados, fórmulas, importes, límites y privacidad OK.');
